import { expect, test } from "@playwright/test";

test("HTTP onboarding waits for legacy templates and retains field/unit/evidence mappings", async ({ page, request }) => {
  const project = `http-setup-${Date.now()}`;
  await request.post("/api/v1/projects", { data: { project_id: project, name: "HTTP onboarding" } });
  const probe = await (await request.get("/api/v1/test-target")).json();
  await page.addInitScript(p => localStorage.setItem("commerce-eval-project", p), project);
  let releaseTemplates!: () => void;
  let templatesFetched!: () => void;
  const holdTemplates = new Promise<void>(resolve => { releaseTemplates = resolve; });
  const fetchedTemplates = new Promise<void>(resolve => { templatesFetched = resolve; });
  await page.route("**/api/v1/scenario-templates?template_version=0.2.0", async route => {
    const response = await route.fetch();
    expect(response.ok()).toBeTruthy();
    const bank = await response.json();
    expect(bank.items).toHaveLength(32);
    expect(bank.items.find((item: { scenario_id: string }) => item.scenario_id === "T01").capabilities).toContain("pricing.audit_margin");
    templatesFetched();
    await holdTemplates;
    await route.fulfill({ response });
  }, { times: 1 });
  await page.goto("/onboarding?bank_version=0.2.0");
  await fetchedTemplates;
  await expect(page.getByLabel("Bank version", { exact: true })).toHaveValue("0.2.0");
  await expect(page.getByRole("button", { name: "Continue", exact: true })).toBeDisabled();
  releaseTemplates();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Endpoint", { exact: true }).fill(probe.url);
  await page.getByLabel("This target is safe for evaluation (dry-run / sandbox only)").check();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  const mapping = page.locator(".capability-mappings > details").filter({ hasText: "pricing.audit_margin" });
  await mapping.locator("summary").click();
  await mapping.getByRole("textbox", { name: /^Tool [0-9]+$/ }).fill("erp.check_margin");
  await mapping.getByRole("button", { name: "Add argument", exact: true }).click();
  await expect(page.getByRole("button", { name: "Continue", exact: true })).toBeDisabled();
  const row = mapping.locator(".mapping-field-row").first();
  await row.getByLabel("Neutral field", { exact: true }).fill("threshold_percent");
  await row.getByLabel("Tool field / pointer", { exact: true }).fill("/options/threshold");
  await row.getByLabel("Unit multiplier", { exact: true }).fill("0.01");
  await mapping.getByRole("button", { name: "Add evidence field", exact: true }).click();
  const evidence = mapping.locator(".mapping-field-row").last();
  await evidence.getByLabel("Neutral field", { exact: true }).fill("status");
  await evidence.getByLabel("Tool field / pointer", { exact: true }).fill("/result/status");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("All 32 scenarios", { exact: true }).uncheck();
  await expect(page.locator(".selection-total")).toContainText("0 / 32");
  await page.locator(".direction-group label").filter({ hasText: "T01" }).locator("input").check();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Check connection", exact: true }).click();
  await expect(page.locator(".wizard-section .json-view")).toContainText('"executed": false');
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("I confirm this configuration and sanitized data.").check();
  await page.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Saved", exact: true })).toBeVisible();
  const datasets = await (await request.get(`/api/v1/datasets?project_id=${project}`)).json();
  expect(datasets.items).toHaveLength(1);
  expect(datasets.items[0].case_count).toBe(1);
  const detail = await (await request.get(`/api/v1/datasets/${project}/${datasets.items[0].dataset_id}/1.0.0`)).json();
  const binding = detail.cases[0].capability_bindings.find((b: { capability_id: string }) => b.capability_id === "pricing.audit_margin");
  expect(binding.tool_id).toBe("erp.check_margin");
  expect(binding.argument_mapping.threshold_percent).toBe("/options/threshold");
  expect(binding.unit_scale.threshold_percent).toBe(0.01);
  expect(binding.evidence_mapping.status).toBe("/result/status");
  expect((await (await request.get("/api/v1/test-target")).json()).executions).toBe(0);
});
